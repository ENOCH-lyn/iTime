@Composable
fun SyncChip(phase: SyncPhase, pending: Int, conflicts: Int) {
    val (icon, label, tint) = when {
        conflicts > 0 -> Triple(Icons.Outlined.Warning, "有 $conflicts 项待处理", MaterialTheme.colorScheme.error)
        pending > 0 -> Triple(Icons.Outlined.Sync, "待同步 $pending", MaterialTheme.colorScheme.tertiary)
        phase == SyncPhase.Offline -> Triple(Icons.Outlined.CloudOff, "离线", MaterialTheme.colorScheme.onSurfaceVariant)
        phase == SyncPhase.Syncing || phase == SyncPhase.Connecting ->
            Triple(Icons.Outlined.Sync, "同步中", MaterialTheme.colorScheme.primary)
        else -> Triple(Icons.Outlined.CloudDone, "已同步", MaterialTheme.colorScheme.secondary)
    }
    Row(verticalAlignment = Alignment.CenterVertically) {
        Icon(icon, contentDescription = null, tint = tint, modifier = Modifier.size(16.dp))
        Spacer(Modifier.width(4.dp))
        Text(label, style = MaterialTheme.typography.labelMedium, color = tint)
    }
}

@Composable
fun ErrorText(message: String?, modifier: Modifier = Modifier) {
    if (message.isNullOrBlank()) return
    Text(
        message,
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.error,
        modifier = modifier.fillMaxWidth(),
    )
}
